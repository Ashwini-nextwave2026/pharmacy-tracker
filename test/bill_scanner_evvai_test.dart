// The same page turned by [deg] degrees, as ML Kit reports a sideways scan
List<RawWord> turned(double deg) {
  final a = deg * math.pi / 180, c = math.cos(a), s = math.sin(a);
  math.Point<num> p(double x, double y) =>
      math.Point(x * c - y * s + 2000, x * s + y * c + 2000);
  return [
    for (final w in evvai)
      (
        text: w.text,
        corners: [p(w.left, w.top), p(w.right, w.top), p(w.right, w.bottom), p(w.left, w.bottom)],
      ),
  ];
}

